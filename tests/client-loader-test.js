const fs = require('fs');
const path = require('path');
const assert = require('assert');

// Dummy browser environment variables
global.window = {};
global.localStorage = {
  store: {},
  getItem(key) { return this.store[key] || null; },
  setItem(key, value) { this.store[key] = String(value); },
  clear() { this.store = {}; }
};

// Mock URLSearchParams
global.URLSearchParams = class {
  constructor(search) {
    this.search = search || "";
  }
  get(key) {
    if (this.search.includes(`${key}=`)) {
      const match = this.search.match(new RegExp(`${key}=([^&]+)`));
      return match ? match[1] : null;
    }
    return null;
  }
};

// Mock document.write to load files in test runner
global.document = {
  write(tag) {
    // Extract src parameter
    const match = tag.match(/src="([^"]+)"/);
    if (match) {
      const filePath = path.join(__dirname, '..', 'active', 'dashboard', match[1]);
      if (fs.existsSync(filePath)) {
        const code = fs.readFileSync(filePath, 'utf8');
        eval(code); // Load the client config.js dynamically into global.window
      } else {
        throw new Error(`File not found: ${filePath}`);
      }
    }
  }
};

function runTest() {
  console.log(`==================================================`);
  console.log(`🧪 Running Client Config Loader Integration Tests`);
  console.log(`==================================================\n`);

  const loaderPath = path.join(__dirname, '..', 'active', 'dashboard', 'client-loader.js');
  const loaderCode = fs.readFileSync(loaderPath, 'utf8');

  // Test Case 1: Parameter-driven resolution for MIE-03
  console.log("Test Case 1: Query parameter ?client=MIE-03");
  global.window.location = { search: "?client=MIE-03" };
  global.window.PMS_CLIENT_CONFIG = undefined;
  global.localStorage.clear();
  eval(loaderCode);
  
  assert.ok(global.window.PMS_CLIENT_CONFIG, "PMS_CLIENT_CONFIG should be loaded");
  assert.equal(global.window.PMS_CLIENT_CONFIG.districtId, "MIE-03");
  assert.equal(global.window.PMS_CLIENT_CONFIG.api.gasWebAppUrl, "https://script.google.com/macros/s/AKfycbxyHvUbJ3yVwXX8sIdK_mWb6ML5ChmFX3mfv-nlEv1DDCv30hBQJlngM096_zLW04vQ/exec");
  assert.equal(global.localStorage.getItem('PMS_ACTIVE_CLIENT'), "MIE-03", "Active client must be saved to LocalStorage");
  console.log("✓ Test Case 1 PASS\n");

  // Test Case 2: Parameter-driven resolution for MIE-04
  console.log("Test Case 2: Query parameter ?client=MIE-04");
  global.window.location = { search: "?client=MIE-04" };
  global.window.PMS_CLIENT_CONFIG = undefined;
  eval(loaderCode);
  
  assert.ok(global.window.PMS_CLIENT_CONFIG, "PMS_CLIENT_CONFIG should be loaded");
  assert.equal(global.window.PMS_CLIENT_CONFIG.districtId, "MIE-04");
  assert.equal(global.localStorage.getItem('PMS_ACTIVE_CLIENT'), "MIE-04");
  console.log("✓ Test Case 2 PASS\n");

  // Test Case 3: Parameter-driven resolution for MIE-05 (Auto-generated by Phase 32)
  console.log("Test Case 3: Query parameter ?client=MIE-05 (Auto-generated)");
  global.window.location = { search: "?client=MIE-05" };
  global.window.PMS_CLIENT_CONFIG = undefined;
  eval(loaderCode);
  
  assert.ok(global.window.PMS_CLIENT_CONFIG, "PMS_CLIENT_CONFIG should be loaded");
  assert.equal(global.window.PMS_CLIENT_CONFIG.districtId, "MIE-05");
  assert.equal(global.localStorage.getItem('PMS_ACTIVE_CLIENT'), "MIE-05");
  console.log("✓ Test Case 3 PASS\n");

  // Test Case 4: Cache-driven fallback (No query param, load from LocalStorage)
  console.log("Test Case 4: Fallback from LocalStorage cache");
  global.window.location = { search: "" }; // No search param
  global.window.PMS_CLIENT_CONFIG = undefined;
  // LocalStorage has MIE-05 saved
  eval(loaderCode);
  
  assert.ok(global.window.PMS_CLIENT_CONFIG, "PMS_CLIENT_CONFIG should be resolved from LocalStorage cache");
  assert.equal(global.window.PMS_CLIENT_CONFIG.districtId, "MIE-05");
  console.log("✓ Test Case 4 PASS\n");

  // Test Case 5: Default fallback (No search param, no LocalStorage)
  console.log("Test Case 5: Default fallback to MIE-03");
  global.window.location = { search: "" };
  global.window.PMS_CLIENT_CONFIG = undefined;
  global.localStorage.clear();
  eval(loaderCode);
  
  assert.ok(global.window.PMS_CLIENT_CONFIG, "PMS_CLIENT_CONFIG should fallback to default client");
  assert.equal(global.window.PMS_CLIENT_CONFIG.districtId, "MIE-03");
  console.log("✓ Test Case 5 PASS\n");

  // Test Case 6: Schema Schema integrity check
  console.log("Test Case 6: Schema Integrity constraints verification");
  const clients = ["MIE-03", "MIE-04", "MIE-05"];
  clients.forEach(c => {
    global.window.location = { search: `?client=${c}` };
    global.window.PMS_CLIENT_CONFIG = undefined;
    eval(loaderCode);
    
    const config = global.window.PMS_CLIENT_CONFIG;
    assert.ok(config.districtId, `config.districtId must exist for ${c}`);
    assert.ok(config.districtName, `config.districtName must exist for ${c}`);
    assert.ok(config.api && config.api.gasWebAppUrl, `config.api.gasWebAppUrl must exist for ${c}`);
    assert.ok(config.line && config.line.liffId, `config.line.liffId must exist for ${c}`);
    assert.ok(config.features && typeof config.features.photoUpload === 'boolean', `config.features.photoUpload must be boolean for ${c}`);
    assert.ok(config.features && typeof config.features.gpsTracking === 'boolean', `config.features.gpsTracking must be boolean for ${c}`);
  });
  console.log("✓ Test Case 6 PASS\n");

  console.log(`==================================================`);
  console.log(`🎉 ALL CLIENT LOADER INTEGRITY TESTS PASSED`);
  console.log(`==================================================`);
}

runTest();
